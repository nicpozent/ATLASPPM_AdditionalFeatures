// ============================================================================
//  UI-chrome translation catalogs (static, offline — no runtime translation
//  service). English is the source; the Nordic languages + French are
//  pre-translated. Anything missing in a locale falls back to English, so the
//  app never shows a blank or a raw key.
//
//  Scope is intentionally UI CHROME ONLY (nav, headings, common controls) —
//  user-entered data (project names, comments, demands) is never translated.
//  A live translation service can be layered on later for dynamic text; this
//  catalog stays the fast, offline baseline.
//
//  Key scheme (flat, dot-namespaced):
//    group.*          sidebar group headings
//    common.*         shared controls (role, export, sign out, language)
//    screen.<id>.label     sidebar label   (also used as the header title when
//                          no screen.<id>.title is present)
//    screen.<id>.title     header title    (only where it differs from label)
//    screen.<id>.subtitle  header subtitle
// ============================================================================

